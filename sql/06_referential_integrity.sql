-- CONTROL GROUP: RI | Read-only independent relationship checks
-- Expected count is 0 for every control. NULL optional references are ignored.
SELECT 'RI-001' AS control_id, 'EMPLOYEES -> JOBS' AS relation,
       COUNT(*) AS orphan_count
FROM HR.EMPLOYEES e
WHERE NOT EXISTS (SELECT 1 FROM HR.JOBS j WHERE j.job_id = e.job_id)
UNION ALL
SELECT 'RI-002', 'EMPLOYEES -> DEPARTMENTS', COUNT(*)
FROM HR.EMPLOYEES e
WHERE e.department_id IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM HR.DEPARTMENTS d WHERE d.department_id = e.department_id)
UNION ALL
SELECT 'RI-003', 'EMPLOYEES -> MANAGERS', COUNT(*)
FROM HR.EMPLOYEES e
WHERE e.manager_id IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM HR.EMPLOYEES m WHERE m.employee_id = e.manager_id)
UNION ALL
SELECT 'RI-004', 'DEPARTMENTS -> LOCATIONS', COUNT(*)
FROM HR.DEPARTMENTS d
WHERE d.location_id IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM HR.LOCATIONS l WHERE l.location_id = d.location_id)
UNION ALL
SELECT 'RI-005', 'LOCATIONS -> COUNTRIES', COUNT(*)
FROM HR.LOCATIONS l
WHERE l.country_id IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM HR.COUNTRIES c WHERE c.country_id = l.country_id)
UNION ALL
SELECT 'RI-006', 'COUNTRIES -> REGIONS', COUNT(*)
FROM HR.COUNTRIES c
WHERE c.region_id IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM HR.REGIONS r WHERE r.region_id = c.region_id)
UNION ALL
SELECT 'RI-007', 'JOB_HISTORY -> JOBS', COUNT(*)
FROM HR.JOB_HISTORY h
WHERE NOT EXISTS (SELECT 1 FROM HR.JOBS j WHERE j.job_id = h.job_id)
UNION ALL
SELECT 'RI-008', 'JOB_HISTORY -> EMPLOYEES', COUNT(*)
FROM HR.JOB_HISTORY h
WHERE NOT EXISTS (SELECT 1 FROM HR.EMPLOYEES e WHERE e.employee_id = h.employee_id)
ORDER BY control_id;
